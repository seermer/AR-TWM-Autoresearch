def entry(table: dict, name) -> tuple | None:
    """`name`'s entry: its own, or its family's ("tool.*" for "tool.ask")."""
    return table.get(name) or table.get(f"{str(name).split('.', 1)[0]}.*")


def component(table: dict, name: str) -> str | None:
    if (found := entry(table, name)) is None:
        raise ValueError(f"unregistered telemetry name {name!r}")
    return found[0]
